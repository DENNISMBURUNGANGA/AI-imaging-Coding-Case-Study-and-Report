class NucleiDataset(Dataset):
    def __init__(self, man, split, augment=False):
        self.rows = man[(man.split==split) & man["mask"].notna()].reset_index(drop=True)
        self.augment = augment
    def __len__(self): return len(self.rows)
    def _aug(self, img, m):
        # Flips and 90-degree rotations only: exact (no interpolation) and
        # applied identically to image and mask, so pairing cannot drift.
        k = np.random.randint(4)
        img, m = np.rot90(img,k), np.rot90(m,k)
        if np.random.rand()<.5: img, m = np.fliplr(img), np.fliplr(m)
        if np.random.rand()<.5: img, m = np.flipud(img), np.flipud(m)
        return np.ascontiguousarray(img), np.ascontiguousarray(m)
    def __getitem__(self, i):
        r = self.rows.iloc[i]
        img = load_image_gray(r["image"]).astype(np.float32)/255.
        m   = load_mask(r["mask"]).astype(np.float32)
        if self.augment: img, m = self._aug(img, m)
        return torch.from_numpy(img).unsqueeze(0), torch.from_numpy(m).unsqueeze(0), r["image_id"]

