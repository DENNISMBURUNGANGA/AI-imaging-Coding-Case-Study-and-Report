def soft_dice_loss(logits, target, eps=1.0):
    """Differentiable Dice on probabilities — no thresholding, so gradients flow."""
    p = torch.sigmoid(logits)
    num = 2*(p*target).sum(dim=(1,2,3)) + eps
    den = p.sum(dim=(1,2,3)) + target.sum(dim=(1,2,3)) + eps
    return 1 - (num/den).mean()

class CombinedLoss(nn.Module):
    """BCE, Dice, or their sum — selectable for the ablation.

    BCE alone is dominated by background when foreground is sparse: an
    all-background prediction scores well on BCE and zero on Dice. Dice alone
    is unstable early. The sum is usually more reliable than either.
    """
    def __init__(self, mode="bce+dice", dice_weight=0.5):
        super().__init__(); assert mode in {"bce","dice","bce+dice"}
        self.mode, self.w, self.bce = mode, dice_weight, nn.BCEWithLogitsLoss()
    def forward(self, logits, target):
        if self.mode=="bce":  return self.bce(logits, target)
        if self.mode=="dice": return soft_dice_loss(logits, target)
        return (1-self.w)*self.bce(logits,target) + self.w*soft_dice_loss(logits,target)

@torch.no_grad()
def evaluate(model, loader, thresh=PRED_THRESH):
    """Macro AND micro. Macro averages per-image scores so every image counts
    equally; micro pools all pixels so dense images dominate. They diverge when
    object density varies, and reporting one without saying which hides that."""
    model.eval(); ds, ios = [], []; inter = ps = ts = 0.0
    for x, y, _ in loader:
        x, y = x.to(DEVICE), y.to(DEVICE)
        lg = model(x); pr = (torch.sigmoid(lg) > thresh).float()
        i_ = (pr*y).sum(dim=(1,2,3)); p_, t_ = pr.sum(dim=(1,2,3)), y.sum(dim=(1,2,3))
        ds.append(((2*i_+1e-7)/(p_+t_+1e-7)).cpu())
        ios.append(((i_+1e-7)/(p_+t_-i_+1e-7)).cpu())
        inter += (pr*y).sum().item(); ps += pr.sum().item(); ts += y.sum().item()
    ds, ios = torch.cat(ds), torch.cat(ios)
    return {"macro_dice": float(ds.mean()), "macro_iou": float(ios.mean()),
            "micro_dice": 2*inter/(ps+ts+1e-7), "micro_iou": inter/(ps+ts-inter+1e-7),
            "dice_std": float(ds.std()) if len(ds)>1 else 0.0,
            "dice_min": float(ds.min()), "dice_max": float(ds.max())}

