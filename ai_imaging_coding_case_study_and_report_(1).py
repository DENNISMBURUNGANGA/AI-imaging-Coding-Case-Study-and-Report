def validate_numbers_record(rec, computed):
    """Validate the record AND check the echoed count against the computed one."""
    if rec is None: return {"valid": False, "n_objects_matches": False}
    missing = [f for f in ["description","n_objects","density_class",
                           "shape_regularity","quality_flag"] if f not in rec]
    viol = []
    if str(rec.get("density_class","")).lower() not in ALLOWED_DENSITY: viol.append("density_class")
    if str(rec.get("shape_regularity","")).lower() not in ALLOWED_SHAPE: viol.append("shape_regularity")
    if str(rec.get("quality_flag","")).lower() not in ALLOWED_QFLAG: viol.append("quality_flag")
    try:    matches = int(rec.get("n_objects",-1)) == int(computed["n_objects"])
    except (TypeError, ValueError): matches = False
    return {"valid": not missing and not viol, "n_objects_matches": matches}

