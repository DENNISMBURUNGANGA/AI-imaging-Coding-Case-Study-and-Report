def query_vlm(prompt, image_path, model=None, seed=None, timeout=REQUEST_TIMEOUT):
    payload = {"model": model or VISION_MODEL, "prompt": prompt,
               "images": [encode_image(image_path)], "stream": False}
    if seed is not None: payload["options"] = {"seed": seed}
    t0 = time.time()
    r = requests.post(f"{OLLAMA_HOST}/api/generate", json=payload, timeout=timeout)
    r.raise_for_status()
    return {"response": r.json().get("response",""), "elapsed_s": round(time.time()-t0,2)}

def extract_json(text):
    """Three strategies, strictest first. The status is kept, not discarded:
    how often a model ignores an explicit output contract is itself a finding."""
    if not text or not text.strip(): return None, "empty"
    try: return json.loads(text.strip()), "clean"
    except json.JSONDecodeError: pass
    m = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    if m:
        try: return json.loads(m.group(1)), "fenced"
        except json.JSONDecodeError: pass
    s = text.find("{")
    if s != -1:
        depth = 0
        for i, ch in enumerate(text[s:], s):
            if ch == "{": depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    try: return json.loads(text[s:i+1]), "embedded"
                    except json.JSONDecodeError: break
    return None, "unparseable"

VLM_FIELDS = ["modality","tissue_type","notable_features","image_quality"]
ALLOWED_MODALITY = {"microscopy","histology","x-ray","ct","mri","ultrasound",
                    "retinal","dermoscopy","other","uncertain"}
ALLOWED_QUALITY = {"good","moderate","poor","uncertain"}

def validate_vlm_record(rec):
    """Schema compliance is measured, not assumed."""
    if rec is None:
        return {"valid": False, "missing": VLM_FIELDS, "violations": [], "n_features": 0}
    missing = [f for f in VLM_FIELDS if f not in rec]
    viol = []
    if str(rec.get("modality","")).lower() not in ALLOWED_MODALITY: viol.append("modality")
    if str(rec.get("image_quality","")).lower() not in ALLOWED_QUALITY: viol.append("image_quality")
    fe = rec.get("notable_features", [])
    return {"valid": not missing and not viol, "missing": missing, "violations": viol,
            "n_features": len(fe) if isinstance(fe, list) else 0}

