def train_unet(loss_mode="bce+dice", epochs=EPOCHS, lr=LR, seed=RANDOM_STATE, verbose=True):
    """Keeps the best-Dice checkpoint, not the final epoch: on 20 validation
    images the score oscillates and the last epoch is not reliably best."""
    torch.manual_seed(seed); np.random.seed(seed)
    model = UNet(1,1,BASE_CH).to(DEVICE)
    crit, opt = CombinedLoss(loss_mode), torch.optim.Adam(model.parameters(), lr=lr)
    sched = torch.optim.lr_scheduler.ReduceLROnPlateau(opt, mode="max", factor=.5, patience=5)
    hist, best, best_state = [], -1.0, None
    for ep in range(1, epochs+1):
        model.train(); run = 0.0
        for x, y, _ in train_dl:
            x, y = x.to(DEVICE), y.to(DEVICE)
            opt.zero_grad(); loss = crit(model(x), y); loss.backward(); opt.step()
            run += loss.item()*x.size(0)
        tr = run/len(train_dl.dataset); val = evaluate(model, val_dl); sched.step(val["macro_dice"])
        hist.append({"epoch": ep, "train_loss": tr, "val_macro_dice": val["macro_dice"],
                     "val_macro_iou": val["macro_iou"], "val_micro_dice": val["micro_dice"]})
        if val["macro_dice"] > best:
            best = val["macro_dice"]
            best_state = {k: v.detach().cpu().clone() for k,v in model.state_dict().items()}
        if verbose and (ep%5==0 or ep==1):
            print(f"  epoch {ep:>3} | loss {tr:.4f} | Dice {val['macro_dice']:.4f} "
                  f"| IoU {val['macro_iou']:.4f}")
    if best_state: model.load_state_dict(best_state)
    return model, pd.DataFrame(hist), best

