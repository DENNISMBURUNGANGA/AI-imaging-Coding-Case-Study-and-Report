def _probe_image(path="/tmp/probe.png"):
    """Two bright discs on a dark field — trivial, but a model that cannot
    report this will not manage real microscopy."""
    yy, xx = np.mgrid[0:256, 0:256]
    img = np.full((256, 256), 30, np.uint8)
    for cy, cx, rad in [(90, 90, 34), (170, 165, 22)]:
        img[(yy-cy)**2 + (xx-cx)**2 < rad**2] = 220
    Image.fromarray(img).save(path)
    return path

def encode_image(path):
    return base64.b64encode(open(path, "rb").read()).decode()

def try_vision_model(name, probe_b64, pull_timeout=2400):
    """Pull, then send a real image. Only a successful generate counts."""
    pull = subprocess.run(["ollama", "pull", name],
                          capture_output=True, text=True, timeout=pull_timeout)
    if pull.returncode != 0:
        return False, (pull.stderr or pull.stdout).strip()[-180:], None
    try:
        t0 = time.time()
        resp = requests.post(f"{OLLAMA_HOST}/api/generate", json={
            "model": name,
            "prompt": "How many bright circular objects are in this image?",
            "images": [probe_b64], "stream": False}, timeout=900)
        if resp.status_code != 200:
            return False, resp.text[:180], None
        txt = resp.json().get("response", "").strip()
        if not txt:
            return False, "empty response", None
        return True, txt, round(time.time() - t0, 1)
    except Exception as e:
        return False, f"{type(e).__name__}: {str(e)[:150]}", None

probe_b64 = encode_image(_probe_image())
