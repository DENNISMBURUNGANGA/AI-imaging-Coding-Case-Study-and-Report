def query_text_llm(prompt, model=None, timeout=REQUEST_TIMEOUT, force_json=True):
    """Text-only call.

    format="json" makes Ollama constrain decoding to syntactically valid JSON.
    Without it, small models echo whatever structure the prompt shows them —
    which is why a pseudo-schema with unquoted values produces 0% parse rate.
    """
    payload = {"model": model or TEXT_MODEL, "prompt": prompt, "stream": False,
               "options": {"temperature": 0.2}}
    if force_json:
        payload["format"] = "json"
    t0 = time.time()
    r = requests.post(f"{OLLAMA_HOST}/api/generate", json=payload, timeout=timeout)
    r.raise_for_status()
    return {"response": r.json().get("response",""), "elapsed_s": round(time.time()-t0,2)}


def extract_json(text):
    """Fences, preamble, trailing commas, and a brace scan that respects string
    literals (so a '{' inside a description does not derail it)."""
    if not text or not text.strip(): return None, "empty"
    t = text.strip()
    if t.startswith("```"):
        t = re.sub(r"^```(?:json)?\s*", "", t); t = re.sub(r"\s*```$", "", t).strip()

    def _try(s):
        try: return json.loads(s)
        except json.JSONDecodeError: pass
        try: return json.loads(re.sub(r",\s*([}\]])", r"\1", s))   # trailing commas
        except json.JSONDecodeError: return None

    got = _try(t)
    if got is not None: return got, "clean"
    m = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    if m:
        got = _try(m.group(1))
        if got is not None: return got, "fenced"
    start = text.find("{")
    if start != -1:
        depth, in_str, esc = 0, False, False
        for i, ch in enumerate(text[start:], start):
            if esc: esc = False; continue
            if ch == "\\" and in_str: esc = True; continue
            if ch == '"': in_str = not in_str; continue
            if in_str: continue
            if ch == "{": depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    got = _try(text[start:i+1])
                    if got is not None: return got, "embedded"
                    break
    return None, "unparseable"


