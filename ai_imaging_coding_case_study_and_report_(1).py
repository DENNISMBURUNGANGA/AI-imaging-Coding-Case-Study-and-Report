def bimodality_coefficient(x):
    x = np.asarray(x, float); n = x.size
    if n < 4: return np.nan
    s = x.std(ddof=1)
    if s == 0: return np.nan
    z = (x-x.mean())/s; skew, kurt = np.mean(z**3), np.mean(z**4)-3.0
    den = kurt + 3.0*((n-1)**2)/((n-2)*(n-3))
    return float((skew**2+1.0)/den) if den else np.nan

