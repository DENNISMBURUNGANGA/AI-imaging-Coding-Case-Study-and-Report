for label, prompt, force in [("naive", NAIVE_PROMPT, False),
                             ("structured", STRUCTURED_PROMPT, True)]:
    texts = []
    for i in range(3):
        payload = {"model": VISION_MODEL, "prompt": prompt,
                   "images": [encode_image(REP_IMAGE)], "stream": False,
                   "options": {"temperature": 0.8}}
        if force:
            payload["format"] = "json"      # never applied to the naive prompt:
                                            # its failure to produce JSON IS the finding
        r = requests.post(f"{OLLAMA_HOST}/api/generate", json=payload, timeout=900)
        t = r.json().get("response", "").strip()
        texts.append(t)
        print(f"  {label} run {i+1}: {len(t)} chars")
    pairs = [jaccard(texts[i], texts[j]) for i in range(3) for j in range(i+1, 3)]
    results[label] = {"mean_chars": int(np.mean([len(t) for t in texts])),
                      "char_sd": round(float(np.std([len(t) for t in texts])), 1),
                      "mean_pairwise_jaccard": round(float(np.mean(pairs)), 3),
                      "identical_pairs": sum(1 for i in range(3) for j in range(i+1,3)
                                             if texts[i] == texts[j])}
    results[label]["_texts"] = texts

var_cmp = pd.DataFrame({k: {kk: vv for kk, vv in v.items() if not kk.startswith("_")}
                        for k, v in results.items()}).T
var_cmp.to_csv(TAB_DIR/"naive_vs_structured_variability.csv")
