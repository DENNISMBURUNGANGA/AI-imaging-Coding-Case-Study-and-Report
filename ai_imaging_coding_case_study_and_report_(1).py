from skimage.morphology import disk, remove_small_objects, remove_small_holes

MIN_OBJECT_AREA, MORPH_RADIUS = 30, 2

# scikit-image renamed morphology params at 0.26; these keep the notebook
# working on whichever version Colab ships.
def _opening(b, se):
    try:    from skimage.morphology import opening;        return opening(b, se)
    except ImportError:
        from skimage.morphology import binary_opening;     return binary_opening(b, se)

def _closing(b, se):
    try:    from skimage.morphology import closing;        return closing(b, se)
    except ImportError:
        from skimage.morphology import binary_closing;     return binary_closing(b, se)

def _drop_small(b, a):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        try:    return remove_small_objects(b, min_size=a)
        except TypeError: return remove_small_objects(b, a)

def _fill_small(b, a):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        try:    return remove_small_holes(b, area_threshold=a)
        except TypeError: return remove_small_holes(b, a)

def segment_otsu(img, min_area=MIN_OBJECT_AREA, morph_radius=MORPH_RADIUS):
    """Otsu threshold + cleanup. Returns (binary_mask, threshold).

    Order matters: opening (erode-dilate) removes specks BEFORE closing
    (dilate-erode) can seal them into objects. The reverse order fuses
    adjacent debris into spurious components the size filter then keeps.
    """
    thresh = threshold_otsu(img)
    b = img > thresh
    se = disk(morph_radius)
    b = _opening(b, se)
    b = _closing(b, se)
    b = _drop_small(b, min_area)
    b = _fill_small(b, min_area)
    return b, float(thresh)

def extract_region_features(binary, intensity_img):
    """Per-object table. Intensity props measured against the grayscale image,
    not the mask, so mean_intensity is a real measurement."""
    labels = label(binary)
    cols = ["label","area","eccentricity","solidity","mean_intensity",
            "perimeter","equivalent_diameter","extent","orientation"]
    if labels.max() == 0:
        return pd.DataFrame(columns=cols)
    return pd.DataFrame(regionprops_table(labels, intensity_image=intensity_img,
                                          properties=tuple(cols)))

def summarise_regions(feat_df, shape=(IMG_SIZE, IMG_SIZE)):
    """Image-level numbers. These are the ONLY quantities the LLM interprets,
    and they are computed here — not by the model."""
    total = shape[0]*shape[1]
    if feat_df.empty:
        return {"n_objects":0,"mean_area":0.0,"median_area":0.0,"std_area":0.0,
                "coverage_pct":0.0,"mean_eccentricity":np.nan,
                "mean_solidity":np.nan,"mean_intensity":np.nan}
    return {"n_objects": int(len(feat_df)),
            "mean_area": round(float(feat_df.area.mean()),2),
            "median_area": round(float(feat_df.area.median()),2),
            "std_area": round(float(feat_df.area.std(ddof=0)),2),
            "coverage_pct": round(100*float(feat_df.area.sum())/total,2),
            "mean_eccentricity": round(float(feat_df.eccentricity.mean()),3),
            "mean_solidity": round(float(feat_df.solidity.mean()),3),
            "mean_intensity": round(float(feat_df.mean_intensity.mean()),2)}

